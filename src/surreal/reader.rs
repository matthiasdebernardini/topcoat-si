//! The record user the `surreal` code-mode pack reads as.

use surrealdb::opt::auth::Record;
use surrealdb::{Connection, Surreal};

use super::store_error;
use crate::error::{Error, Result};

const ACCESS: &str = "topcoat_pack";

// The reader's account. A record user sees only what a table's permissions grant it, and
// `DEFINE TABLE` grants nothing by default. The session never expires (`FOR SESSION NONE`), so
// the reader never has to sign in again.
const DEFINE_READER: &str = "\
    DEFINE TABLE IF NOT EXISTS topcoat_pack_user TYPE NORMAL SCHEMAFULL PERMISSIONS NONE; \
    DEFINE FIELD IF NOT EXISTS pass ON topcoat_pack_user TYPE string; \
    DEFINE ACCESS IF NOT EXISTS topcoat_pack ON DATABASE TYPE RECORD \
        SIGNIN (SELECT * FROM topcoat_pack_user \
                WHERE id = topcoat_pack_user:reader AND crypto::argon2::compare(pass, $pass)) \
        DURATION FOR TOKEN 1h, FOR SESSION NONE;";

// A fresh secret on every build, generated by the engine.
const ROTATE_SECRET: &str = "\
    LET $p = rand::string(40); \
    UPSERT topcoat_pack_user:reader SET pass = crypto::argon2::generate($p); \
    RETURN $p;";

/// A session signed in as a record user that can read only what the app's table permissions
/// grant it, for the [`surreal` pack](crate::code_mode::packs::surreal).
///
/// Build one per app and share it across conversations: building it rotates the secret the
/// reader signs in with, so concurrent builds race. It holds a session that never expires, and
/// `db` itself, which keeps its own session and permissions, is untouched.
pub struct Reader<C: Connection> {
    root: Surreal<C>,
    session: Surreal<C>,
}

impl<C: Connection> Reader<C> {
    /// Defines the reader's access method if it is missing, sets a fresh secret and signs in on
    /// a session of its own. `db` must be signed in as a user that can define an access method
    /// (an embedded handle is), and `namespace` and `database` are the ones it has selected.
    ///
    /// # Errors
    ///
    /// [`ErrorKind::Store`](crate::ErrorKind::Store) when defining the reader or signing in
    /// fails.
    pub async fn try_new(db: Surreal<C>, namespace: &str, database: &str) -> Result<Self> {
        let store = |context: &str| {
            let context = context.to_string();
            move |error| store_error(context, error)
        };
        db.query(DEFINE_READER)
            .await
            .and_then(surrealdb::IndexedResults::check)
            .map_err(store("defining the surreal pack's reader"))?;
        let mut response = db
            .query(ROTATE_SECRET)
            .await
            .map_err(store("setting the surreal pack's secret"))?;
        let pass: Option<String> = response
            .take(2)
            .map_err(store("setting the surreal pack's secret"))?;
        let pass =
            pass.ok_or_else(|| Error::store("the surreal pack's secret was not set", None))?;
        let session = db.clone();
        session
            .signin(Record {
                namespace: namespace.to_string(),
                database: database.to_string(),
                access: ACCESS.to_string(),
                params: serde_json::json!({"pass": pass}),
            })
            .await
            .map_err(store("signing in the surreal pack's reader"))?;
        Ok(Self { root: db, session })
    }

    /// The signed-in handle. Clone it for each use.
    pub(crate) fn session(&self) -> Surreal<C> {
        self.session.clone()
    }

    /// The app's own handle, for `INFO` statements a record user cannot run.
    pub(crate) fn root(&self) -> Surreal<C> {
        self.root.clone()
    }
}
